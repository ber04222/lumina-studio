const { chromium, devices } = require('playwright');
const S = (process.env.SHOTS || 'shots');
const M = require('path').join(__dirname, '../media/');
(async () => {
  const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const ctx = await b.newContext({ ...devices['iPhone 13'], acceptDownloads: true });
  await ctx.route(/fonts\.(googleapis|gstatic)\.com/, (r) => r.abort());
  const p = await ctx.newPage();
  const errs = [];
  p.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.type() + ': ' + m.text().slice(0, 300)); });
  p.on('pageerror', (e) => errs.push('pageerror: ' + e.message));
  const shot = async (n) => { await p.waitForTimeout(700); await p.screenshot({ path: `${S}/${n}.png` }); };
  await p.goto('http://localhost:5173/');
  await shot('m00-home');
  await p.getByRole('button', { name: /Photo/ }).first().click();
  await p.waitForTimeout(500);
  await p.locator('input[type=file][accept="image/*"]').setInputFiles([M + 'chelsea.png', M + 'coffee.png', M + 'overcast.png']);
  await p.waitForTimeout(2500);
  await shot('m01-library');
  await p.getByRole('button', { name: 'overcast.png' }).click();
  await p.waitForTimeout(2500);
  await shot('m02-editor');
  await p.getByRole('button', { name: /Auto/ }).click();
  await shot('m03-auto');
  for (const c of ['Color', 'Mix', 'Grading', 'Curve', 'Effects']) { await p.getByRole('tab', { name: c, exact: true }).click(); await shot('m04-' + c.toLowerCase()); }
  await p.getByRole('button', { name: 'Masking' }).click();
  await shot('m05-masks');
  await p.getByRole('button', { name: 'Sky', exact: true }).first().click();
  await p.waitForTimeout(6000);
  await shot('m06-sky');
  await p.getByRole('button', { name: 'Presets' }).click();
  await p.waitForTimeout(2500);
  await shot('m07-presets');
  await p.getByRole('button', { name: 'Remove' }).click();
  const box = await p.locator('canvas').first().boundingBox();
  await p.mouse.move(box.x + box.width * 0.5, box.y + box.height * 0.6);
  await p.mouse.down(); await p.mouse.move(box.x + box.width * 0.55, box.y + box.height * 0.62, { steps: 5 }); await p.mouse.up();
  await shot('m08-remove');
  await p.getByRole('button', { name: 'Crop' }).click();
  await p.getByRole('button', { name: '4:5' }).click();
  await shot('m09-crop');
  await p.getByRole('button', { name: 'Match' }).click();
  await p.waitForTimeout(500);
  await p.getByRole('button', { name: 'chelsea.png' }).click();
  await p.waitForTimeout(2500);
  await shot('m10-match');
  await p.getByRole('button', { name: 'Export' }).click();
  await shot('m11-export');
  const [dl] = await Promise.all([p.waitForEvent('download', { timeout: 60000 }), p.getByRole('button', { name: /Save to device/ }).click()]);
  const path = `${S}/export-${dl.suggestedFilename()}`; await dl.saveAs(path); console.log('download', path);
  await shot('m12-after-export');
  // reload: persistence
  await p.reload(); await p.waitForTimeout(2500); await shot('m13-reload');
  console.log('ERRORS:\n' + errs.join('\n'));
  await b.close();
})().catch((e) => { console.error('FAILED', e); process.exit(1); });
